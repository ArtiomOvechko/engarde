using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Security.Cryptography;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Engarde.Generators;

[Generator]
public sealed class GuardGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor Unsupported = new(
        "EG1001", "Cannot generate inline guard methods", "Cannot generate inline methods for '{0}': {1}",
        "Engarde", DiagnosticSeverity.Error, true);

    private static readonly DiagnosticDescriptor UnsupportedParameter = new(
        "EG1002", "Cannot guard a by-reference parameter",
        "Cannot apply a guard to parameter '{0}': ref, in and out parameters are unsupported; pass it by value or guard the method instead",
        "Engarde", DiagnosticSeverity.Error, true);

    private static readonly DiagnosticDescriptor FeatureBoundGuardMustBeSealed = new(
        "EG1003", "Feature-bound guard must be sealed",
        "Feature-bound guard '{0}' must be sealed because derived guards cannot select another feature",
        "Engarde", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterSourceOutput(context.CompilationProvider, static (output, compilation) =>
        {
            var core = compilation.GetTypeByMetadataName("Engarde.Engarde");
            if (core is not null && SymbolEqualityComparer.Default.Equals(core.ContainingAssembly, compilation.Assembly))
                output.AddSource("IEngarde.g.cs", SourceText.From("""
                    // <auto-generated/>
                    #nullable enable
                    namespace Engarde;
                    public interface IEngarde
                    {
                        global::System.Threading.Tasks.ValueTask<bool> IsFeatureEnabledAsync(string featureFlagName);
                        global::System.Threading.Tasks.ValueTask<bool> IsFeatureEnabledAsync(string featureFlagName, global::System.Threading.CancellationToken cancellationToken);
                    }
                    """, Encoding.UTF8));
        });

        var parameters = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is ParameterSyntax { AttributeLists.Count: > 0 },
            static (syntax, cancellation) => syntax.SemanticModel.GetDeclaredSymbol((ParameterSyntax)syntax.Node, cancellation) as IParameterSymbol);
        context.RegisterSourceOutput(parameters, static (output, parameter) =>
        {
            if (parameter is null || parameter.RefKind == RefKind.None)
                return;

            var guard = parameter.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass is { } type &&
                (type.ToDisplayString() == "Engarde.EngardeAttribute" || IsGuard(type)));
            if (guard is not null)
                output.ReportDiagnostic(Diagnostic.Create(UnsupportedParameter,
                    guard.ApplicationSyntaxReference?.GetSyntax(output.CancellationToken).GetLocation()
                        ?? parameter.Locations.FirstOrDefault(), parameter.Name));
        });

        var candidates = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is TypeDeclarationSyntax type && type.BaseList is not null,
            static (syntax, cancellation) => syntax.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)syntax.Node, cancellation) as INamedTypeSymbol);
        context.RegisterSourceOutput(candidates.Collect().Combine(context.CompilationProvider), static (output, input) =>
        {
            var seen = new HashSet<string>();
            var registrations = new List<(string Service, string Implementation)>();
            foreach (var symbol in input.Left)
            {
                if (symbol is null || !seen.Add(symbol.ToDisplayString()) || !IsGuard(symbol) || symbol.IsAbstract)
                    continue;
                // Existing non-partial attribute implementations remain valid without opting into generation.
                if (!IsPartial(symbol)) continue;
                if (GetGeneratedFeatures(symbol) is { } features)
                {
                    GenerateFeatureBoundGuards(output, symbol, features, input.Right, registrations);
                    continue;
                }
                if (!symbol.IsSealed && symbol.InstanceConstructors.Any(ctor => !ConstructorForwardsFeatures(ctor, input.Right)))
                {
                    output.ReportDiagnostic(Diagnostic.Create(FeatureBoundGuardMustBeSealed,
                        symbol.Locations.FirstOrDefault(), symbol.Name));
                    continue;
                }
                Generate(output, symbol, input.Right, registrations);
            }
            GenerateRegistrations(output, registrations);
        });
    }

    internal static bool IsGuard(INamedTypeSymbol symbol)
    {
        for (var parent = symbol.BaseType; parent is not null; parent = parent.BaseType)
            if (parent.ToDisplayString() == "Engarde.EngardeAttribute") return true;
        return false;
    }

    private static bool IsPartial(INamedTypeSymbol symbol) => symbol.DeclaringSyntaxReferences.Any(
        reference => reference.GetSyntax() is TypeDeclarationSyntax type && type.Modifiers.Any(SyntaxKind.PartialKeyword));

    private static string[]? GetGeneratedFeatures(INamedTypeSymbol symbol)
    {
        var attribute = symbol.GetAttributes().FirstOrDefault(value =>
            value.AttributeClass?.ToDisplayString() == "Engarde.GenerateFeatureGuardsAttribute");
        if (attribute is null) return null;
        return attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Kind == TypedConstantKind.Array
            ? attribute.ConstructorArguments[0].Values.Select(value => value.Value as string ?? "").ToArray()
            : [];
    }

    internal static bool ConstructorForwardsFeatures(IMethodSymbol constructor, Compilation compilation)
    {
        var featureParameter = constructor.Parameters.LastOrDefault();
        return featureParameter is not null &&
            (featureParameter.Type.SpecialType == SpecialType.System_String ||
             featureParameter.Type is IArrayTypeSymbol names && names.ElementType.SpecialType == SpecialType.System_String) &&
            ForwardsFeatureNames(featureParameter, compilation,
                new HashSet<IParameterSymbol>(SymbolEqualityComparer.Default));
    }

    private static void GenerateFeatureBoundGuards(
        SourceProductionContext output, INamedTypeSymbol template, string[] features, Compilation compilation,
        List<(string Service, string Implementation)> registrations)
    {
        if (template.TypeKind != TypeKind.Class || template.IsSealed)
        {
            Error(output, template, "feature guard templates must be non-sealed classes");
            return;
        }
        if (features.Length == 0)
        {
            Error(output, template, "feature guard templates need at least one feature name");
            return;
        }
        var chain = new Stack<INamedTypeSymbol>();
        for (var current = template; current is not null; current = current.ContainingType)
        {
            if (!IsPartial(current))
            {
                Error(output, template, "containing types must also be partial");
                return;
            }
            chain.Push(current);
        }
        var constructors = template.InstanceConstructors
            .Where(constructor => CanExposeConstructor(constructor, template))
            .ToArray();
        if (constructors.Length == 0)
        {
            Error(output, template, "feature guard templates need an accessible constructor");
            return;
        }

        var generatedNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var feature in features)
        {
            var prefix = PascalCase(feature);
            if (prefix.Length == 0 || !SyntaxFacts.IsValidIdentifier(prefix + template.Name))
            {
                Error(output, template, $"feature name '{feature}' cannot form a guard class name");
                return;
            }
            var className = prefix + template.Name;
            if (!generatedNames.Add(className))
            {
                Error(output, template, $"multiple feature names produce the class name '{className}'");
                return;
            }
            GenerateFeatureBoundGuard(output, template, chain, constructors, feature, className, compilation, registrations);
        }
    }

    private static void GenerateFeatureBoundGuard(
        SourceProductionContext output, INamedTypeSymbol template, Stack<INamedTypeSymbol> chain,
        IMethodSymbol[] constructors, string feature, string className, Compilation compilation,
        List<(string Service, string Implementation)> registrations)
    {
        var contract = new StringBuilder();
        var methods = new StringBuilder();
        var generatedConstructors = new StringBuilder();
        var signatures = new HashSet<string>();
        var scopeQueries = new List<ScopeQuery>();
        var literal = SymbolDisplay.FormatLiteral(feature, true);
        foreach (var constructor in constructors)
        {
            if (constructor.Parameters.Any(parameter => parameter.RefKind != RefKind.None ||
                parameter.Type.TypeKind is TypeKind.Pointer or TypeKind.FunctionPointer))
            {
                Error(output, template, "constructors with ref, in, out or pointer parameters are unsupported");
                return;
            }
            var forwardsFeatures = ConstructorForwardsFeatures(constructor, compilation);
            var settings = constructor.Parameters.ToList();
            var featureParameter = forwardsFeatures ? settings[settings.Count - 1] : null;
            if (forwardsFeatures) settings.RemoveAt(settings.Count - 1);
            var signature = string.Join(",", settings.Select(parameter => TypeName(parameter.Type)));
            if (!signatures.Add(signature))
            {
                Error(output, template, "constructors produce duplicate generated feature-bound signatures");
                return;
            }
            var declarations = settings.Select(parameter =>
                TypeName(parameter.Type) + " " + Escape(parameter.Name)).ToList();
            var arguments = settings.Select(parameter => Escape(parameter.Name)).ToList();
            var baseArguments = new List<string>(arguments);
            if (featureParameter is not null)
                baseArguments.Add(featureParameter.Type is IArrayTypeSymbol
                    ? "new string[] { " + literal + " }" : literal);
            generatedConstructors.Append("public ").Append(Escape(className)).Append('(')
                .Append(string.Join(", ", declarations)).Append(") : base(")
                .Append(string.Join(", ", baseArguments)).Append(") { }\n");
            AppendFallbackConstructors(generatedConstructors, "public", className, declarations, arguments);
            AppendGuardedValueConstructor(generatedConstructors, "public", className, declarations, [], arguments);
            var instance = "new " + Escape(className) + "(" + string.Join(", ", arguments) + ")";
            AppendQuery(contract, methods, declarations, instance);
            scopeQueries.Add(new ScopeQuery(settings.Select(parameter => TypeName(parameter.Type)).ToList(),
                settings.Select(parameter => parameter.Name).ToList(), declarations, instance));
        }
        AppendScopeQueries(contract, methods, signatures, scopeQueries, template);

        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!template.ContainingNamespace.IsGlobalNamespace)
            source.Append("namespace ").Append(template.ContainingNamespace.ToDisplayString()).Append(" {\n");
        foreach (var type in chain.Take(chain.Count - 1)) AppendPartial(source, type);

        var interfaceName = "I" + className;
        source.Append(AccessibilityText(template.DeclaredAccessibility)).Append(" interface ")
            .Append(Escape(interfaceName)).Append(TypeParameters(template)).Append(Constraints(template))
            .Append(" {\n").Append(contract).Append("}\n");
        source.Append(AccessibilityText(template.DeclaredAccessibility)).Append(" sealed class ")
            .Append(Escape(className)).Append(TypeParameters(template)).Append(" : ")
            .Append(TypeName(template)).Append(Constraints(template)).Append(" {\n")
            .Append("public override global::System.Collections.Generic.IReadOnlyList<string> FeatureNames { get; } = new string[] { ")
            .Append(literal).Append(" };\n").Append(generatedConstructors);

        var container = template.ContainingType is not null ? TypeName(template.ContainingType) + "."
            : template.ContainingNamespace.IsGlobalNamespace ? "global::"
                : "global::" + template.ContainingNamespace.ToDisplayString() + ".";
        var interfaceType = container + Escape(interfaceName) + TypeParameters(template);
        source.Append("public static ").Append(interfaceType)
            .Append(" CreateInstance() => new __EngardeQueries(global::Engarde.Engarde.CreateInstance());\n")
            .Append("public static ").Append(interfaceType)
            .Append(" CreateInstance(global::System.IServiceProvider services, global::Microsoft.Extensions.DependencyInjection.ServiceLifetime lifetime = global::Microsoft.Extensions.DependencyInjection.ServiceLifetime.Scoped)")
            .Append(" => new __EngardeQueries(global::Engarde.Engarde.CreateInstance(services, lifetime));\n")
            .Append("public sealed class __EngardeQueries : ").Append(interfaceType).Append(" {\n")
            .Append("private readonly global::Engarde.Engarde _queries;\n")
            .Append("public __EngardeQueries(global::Engarde.Engarde queries) { _queries = queries; }\n")
            .Append(methods).Append("}\n}\n");
        foreach (var _ in chain.Take(chain.Count - 1)) source.Append("}\n");
        if (!template.ContainingNamespace.IsGlobalNamespace) source.Append("}\n");

        using var hash = SHA256.Create();
        var hint = className + "." + string.Concat(hash.ComputeHash(Encoding.UTF8.GetBytes(
            template.ToDisplayString() + "|" + feature)).Select(value => value.ToString("x2")));
        output.AddSource(hint + ".Engarde.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        AddRegistration(registrations, template, interfaceName, className);
    }

    private static string PascalCase(string value)
    {
        var result = new StringBuilder(value.Length);
        var capitalize = true;
        foreach (var character in value)
        {
            if (!char.IsLetterOrDigit(character))
            {
                capitalize = true;
                continue;
            }
            result.Append(capitalize ? char.ToUpperInvariant(character) : character);
            capitalize = false;
        }
        return result.ToString();
    }

    private static void Generate(SourceProductionContext output, INamedTypeSymbol symbol, Compilation compilation,
        List<(string Service, string Implementation)> registrations)
    {
        var chain = new Stack<INamedTypeSymbol>();
        for (var current = symbol; current is not null; current = current.ContainingType)
        {
            if (!IsPartial(current))
            {
                Error(output, symbol, "containing types must also be partial");
                return;
            }
            chain.Push(current);
        }

        var contract = new StringBuilder();
        var methods = new StringBuilder();
        var fallbackConstructors = new StringBuilder();
        var signatures = new HashSet<string>();
        var scopeQueries = new List<ScopeQuery>();
        foreach (var ctor in symbol.InstanceConstructors.Where(constructor => CanExposeConstructor(constructor, symbol)))
        {
            if (ctor.Parameters.Any(p => p.RefKind != RefKind.None || p.Type.TypeKind is TypeKind.Pointer or TypeKind.FunctionPointer))
            {
                Error(output, symbol, "constructors with ref, in, out or pointer parameters are unsupported");
                return;
            }
            var parameters = ctor.Parameters.ToList();
            var features = parameters.LastOrDefault();
            bool replaceFeatures = features is not null &&
                (features.Type.SpecialType == SpecialType.System_String ||
                 features.Type is IArrayTypeSymbol names && names.ElementType.SpecialType == SpecialType.System_String) &&
                ForwardsFeatureNames(features, compilation, new HashSet<IParameterSymbol>(SymbolEqualityComparer.Default));
            if (replaceFeatures) parameters.RemoveAt(parameters.Count - 1);
            var declarations = parameters.Select(p => TypeName(p.Type) + " " + Escape(p.Name)).ToList();
            var arguments = parameters.Select(p => Escape(p.Name)).ToList();
            string? flagName = null;
            if (replaceFeatures)
            {
                flagName = "featureFlagName";
                while (parameters.Any(p => p.Name == flagName)) flagName = "_" + flagName;
                declarations.Add("string " + flagName);
                arguments.Add(features!.Type is IArrayTypeSymbol ? "new string[] { " + flagName + " }" : flagName);
            }
            var types = parameters.Select(p => TypeName(p.Type))
                .Concat(replaceFeatures ? new[] { "string" } : Array.Empty<string>()).ToList();
            if (!signatures.Add(string.Join(",", types)))
            {
                Error(output, symbol, "constructors produce duplicate inline method signatures");
                return;
            }
            var instance = "new " + TypeName(symbol) + "(" + string.Join(", ", arguments) + ")";
            var queryArguments = replaceFeatures ? instance + ", " + flagName! : instance;
            AppendQuery(contract, methods, declarations, queryArguments);
            scopeQueries.Add(new ScopeQuery(types, parameters.Select(p => p.Name).Concat(flagName is null ? Array.Empty<string>() : new[] { flagName }).ToList(),
                declarations, queryArguments));

            var constructorDeclarations = ctor.Parameters.Select(ParameterDeclaration).ToList();
            var constructorArguments = ctor.Parameters.Select(parameter => Escape(parameter.Name)).ToList();
            if (ctor.IsImplicitlyDeclared)
                fallbackConstructors.Append(AccessibilityText(ctor.DeclaredAccessibility)).Append(' ')
                    .Append(Escape(symbol.Name)).Append("() { }\n");
            AppendFallbackConstructors(fallbackConstructors, AccessibilityText(ctor.DeclaredAccessibility),
                symbol.Name, constructorDeclarations, constructorArguments);

            var valueDeclarations = parameters.Select(parameter =>
                TypeName(parameter.Type) + " " + Escape(parameter.Name)).ToList();
            var valueArguments = parameters.Select(parameter => Escape(parameter.Name)).ToList();
            var featureDeclarations = new List<string>();
            if (replaceFeatures)
            {
                featureDeclarations.Add(ParameterDeclaration(features!));
                valueArguments.Add(Escape(features!.Name));
            }
            AppendGuardedValueConstructor(fallbackConstructors, AccessibilityText(ctor.DeclaredAccessibility),
                symbol.Name, valueDeclarations, featureDeclarations, valueArguments);
        }
        AppendScopeQueries(contract, methods, signatures, scopeQueries, symbol);

        // A partial attribute can opt into generation while keeping every constructor less accessible than
        // its generated contract. It remains a valid attribute, but has no injectable/query API to expose.
        if (signatures.Count == 0)
            return;

        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!symbol.ContainingNamespace.IsGlobalNamespace)
            source.Append("namespace ").Append(symbol.ContainingNamespace.ToDisplayString()).Append(" {\n");
        foreach (var type in chain.Take(chain.Count - 1)) AppendPartial(source, type);

        var interfaceName = "I" + symbol.Name;
        source.Append(AccessibilityText(symbol.DeclaredAccessibility)).Append(" interface ").Append(Escape(interfaceName))
            .Append(TypeParameters(symbol)).Append(Constraints(symbol)).Append(" {\n").Append(contract).Append("}\n");

        AppendPartial(source, symbol);
        source.Append(fallbackConstructors);
        var container = symbol.ContainingType is not null ? TypeName(symbol.ContainingType) + "."
            : symbol.ContainingNamespace.IsGlobalNamespace ? "global::" : "global::" + symbol.ContainingNamespace.ToDisplayString() + ".";
        var interfaceType = container + Escape(interfaceName) + TypeParameters(symbol);
        var baseType = symbol.BaseType;
        var hidesFactory = baseType is not null && (baseType.GetMembers("CreateInstance").Any(member => member.IsStatic)
            || (IsGuard(baseType) && !baseType.IsAbstract && IsPartial(baseType)));
        var factoryModifiers = hidesFactory ? "public new static " : "public static ";
        var queryTypeModifiers = hidesFactory ? "public new sealed class " : "public sealed class ";
        source.Append(factoryModifiers).Append(interfaceType)
            .Append(" CreateInstance() => new __EngardeQueries(global::Engarde.Engarde.CreateInstance());\n")
            .Append(factoryModifiers).Append(interfaceType)
            .Append(" CreateInstance(global::System.IServiceProvider services, global::Microsoft.Extensions.DependencyInjection.ServiceLifetime lifetime = global::Microsoft.Extensions.DependencyInjection.ServiceLifetime.Scoped)")
            .Append(" => new __EngardeQueries(global::Engarde.Engarde.CreateInstance(services, lifetime));\n")
            .Append(queryTypeModifiers).Append("__EngardeQueries : ").Append(interfaceType).Append(" {\n")
            .Append("private readonly global::Engarde.Engarde _queries;\n")
            .Append("public __EngardeQueries(global::Engarde.Engarde queries) { _queries = queries; }\n")
            .Append(methods).Append("}\n");
        foreach (var _ in chain) source.Append("}\n");
        if (!symbol.ContainingNamespace.IsGlobalNamespace) source.Append("}\n");
        // Encode the full identity to avoid collisions between nested types and namespaces.
        using var hash = SHA256.Create();
        var hint = symbol.Name + "." + string.Concat(hash.ComputeHash(Encoding.UTF8.GetBytes(symbol.ToDisplayString()))
            .Select(b => b.ToString("x2")));
        output.AddSource(hint + ".Engarde.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        AddRegistration(registrations, symbol, interfaceName, symbol.Name);
    }

    private static void AddRegistration(List<(string Service, string Implementation)> registrations,
        INamedTypeSymbol context, string interfaceName, string className)
    {
        if (!RegistrationAccessible(context)) return;
        var container = OpenContainer(context);
        var arguments = OpenArguments(context.Arity);
        registrations.Add((container + Escape(interfaceName) + arguments,
            container + Escape(className) + arguments + ".__EngardeQueries"));
    }

    private static void AppendFallbackConstructors(StringBuilder source, string accessibility, string className,
        List<string> declarations, List<string> arguments)
    {
        var suffix = declarations.Count == 0 ? "" : ", " + string.Join(", ", declarations);
        var forwarded = string.Join(", ", arguments);
        source.Append("[global::Engarde.EngardeFallbackConstructor(global::Engarde.EngardeFallbackKind.Type)]\n")
            .Append(accessibility).Append(' ').Append(Escape(className))
            .Append("(global::System.Type fallbackType").Append(suffix).Append(") : this(")
            .Append(forwarded).Append(") { ConfigureFallback(fallbackType, null); }\n")
            .Append("[global::Engarde.EngardeFallbackConstructor(global::Engarde.EngardeFallbackKind.Method)]\n")
            .Append(accessibility).Append(' ').Append(Escape(className))
            .Append("(string fallbackMethod, global::System.Type fallbackType").Append(suffix).Append(") : this(")
            .Append(forwarded).Append(") { ConfigureFallback(fallbackType, fallbackMethod); }\n");
    }

    private static void AppendGuardedValueConstructor(StringBuilder source, string accessibility, string className,
        List<string> declarations, List<string> featureDeclarations, List<string> arguments)
    {
        var valueName = "guardedValue";
        while (declarations.Concat(featureDeclarations)
               .Any(declaration => declaration.EndsWith(" " + valueName, StringComparison.Ordinal)))
            valueName = "_" + valueName;
        var parameters = declarations.Concat(new[] { "object? " + valueName }).Concat(featureDeclarations);
        source.Append("[global::Engarde.EngardeValueConstructor]\n")
            .Append(accessibility).Append(' ').Append(Escape(className)).Append('(')
            .Append(string.Join(", ", parameters)).Append(") : this(")
            .Append(string.Join(", ", arguments)).Append(") { ConfigureGuardedValue(")
            .Append(valueName).Append("); }\n");
    }

    private static string ParameterDeclaration(IParameterSymbol parameter) =>
        (parameter.IsParams ? "params " : "") + TypeName(parameter.Type) + " " + Escape(parameter.Name);

    private static void GenerateRegistrations(SourceProductionContext output,
        List<(string Service, string Implementation)> registrations)
    {
        if (registrations.Count == 0) return;
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n")
            .Append("internal static class __EngardeGeneratedQueryRegistrations {\n")
            .Append("[global::System.Runtime.CompilerServices.ModuleInitializer]\n")
            .Append("internal static void Register() {\n");
        foreach (var registration in registrations.Distinct())
            source.Append("global::Engarde.EngardeGeneratedQueryRegistration.Add(typeof(")
                .Append(registration.Service).Append("), typeof(")
                .Append(registration.Implementation).Append("));\n");
        source.Append("}\n}\n");
        output.AddSource("Engarde.GeneratedQueryRegistrations.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    private static bool RegistrationAccessible(INamedTypeSymbol type)
    {
        for (var current = type; current is not null; current = current.ContainingType)
            if (current.DeclaredAccessibility is Accessibility.Private or Accessibility.Protected or Accessibility.ProtectedAndInternal)
                return false;
        return true;
    }

    private static string OpenContainer(INamedTypeSymbol type)
    {
        var result = new StringBuilder("global::");
        if (!type.ContainingNamespace.IsGlobalNamespace)
            result.Append(type.ContainingNamespace.ToDisplayString()).Append('.');
        var containing = new Stack<INamedTypeSymbol>();
        for (var current = type.ContainingType; current is not null; current = current.ContainingType)
            containing.Push(current);
        foreach (var current in containing)
            result.Append(Escape(current.Name)).Append(OpenArguments(current.Arity)).Append('.');
        return result.ToString();
    }

    private static string OpenArguments(int arity) => arity == 0 ? "" : "<" + new string(',', arity - 1) + ">";

    // Each query also gets an overload taking a cancellation token
    private static void AppendQuery(StringBuilder contract, StringBuilder methods, List<string> parameters, string arguments,
        string? typeArguments = null, string? typeParameters = null)
    {
        var tokenName = "cancellationToken";
        while (parameters.Any(parameter => parameter.EndsWith(" " + tokenName, StringComparison.Ordinal))) tokenName = "_" + tokenName;
        AppendQueryMethod(contract, methods, parameters, arguments, typeArguments, typeParameters);
        AppendQueryMethod(contract, methods, parameters.Concat(new[] { "global::System.Threading.CancellationToken " + tokenName }).ToList(),
            arguments + ", " + tokenName, typeArguments, typeParameters);
    }

    private static void AppendQueryMethod(StringBuilder contract, StringBuilder methods, List<string> parameters, string arguments,
        string? typeArguments, string? typeParameters)
    {
        var signature = "global::System.Threading.Tasks.ValueTask<bool> IsFeatureEnabledAsync" + typeParameters + "("
            + string.Join(", ", parameters) + ")";
        contract.Append(signature).Append(";\n");
        methods.Append("public ").Append(signature).Append(" => this._queries.IsFeatureEnabledAsync")
            .Append(typeArguments).Append('(').Append(arguments).Append(");\n");
    }

    // The feature scope id type a guard's queries accept: its own, from EngardeAttribute<TProvider, TScopeId> or
    // <TStore, TProvider, TScopeId>, or null for the registered store's. False for its own store without a feature scope.
    private static bool TryGetScopeIdType(INamedTypeSymbol symbol, out ITypeSymbol? scopeIdType)
    {
        scopeIdType = null;
        for (var parent = symbol.BaseType; parent is not null; parent = parent.BaseType)
        {
            if (parent.Name != "EngardeAttribute" || parent.ContainingNamespace.ToDisplayString() != "Engarde") continue;
            if (parent.Arity == 1) return false;
            if (parent.Arity is 2 or 3) scopeIdType = parent.TypeArguments[parent.Arity - 1];
            return true;
        }
        return false;
    }

    // Each constructor query also gets an overload that takes the feature scope id instead of resolving it.
    // A constructor query with the same signature takes precedence over a scope overload. A guard without its own
    // scope id type uses the registered store's, known only at runtime, so its overload is generic.
    private static void AppendScopeQueries(StringBuilder contract, StringBuilder methods, HashSet<string> signatures,
        List<ScopeQuery> queries, INamedTypeSymbol guard)
    {
        if (!TryGetScopeIdType(guard, out var scopeIdType)) return;
        var scopeType = scopeIdType is null ? null : TypeName(scopeIdType);
        var guardTypeParameters = new HashSet<string>();
        for (var current = guard; current is not null; current = current.ContainingType)
            guardTypeParameters.UnionWith(current.TypeParameters.Select(parameter => parameter.Name));
        foreach (var query in queries)
        {
            var scopeName = "scopeId";
            while (query.Names.Contains(scopeName)) scopeName = "_" + scopeName;
            if (scopeType is not null)
            {
                if (!signatures.Add(string.Join(",", query.Types.Concat(new[] { scopeType })))) continue;
                AppendQuery(contract, methods, query.Declarations.Concat(new[] { scopeType + " " + scopeName }).ToList(),
                    query.Arguments + ", " + scopeName, "<" + scopeType + ">");
                continue;
            }
            // A non-generic constructor query with one more parameter would silently take the scope id argument.
            if (queries.Any(other => other.Types.Count == query.Types.Count + 1 &&
                    other.Types.Take(query.Types.Count).SequenceEqual(query.Types)))
                continue;
            var typeParameter = "TFeatureScopeId";
            while (guardTypeParameters.Contains(typeParameter) || query.Names.Contains(typeParameter))
                typeParameter = "_" + typeParameter;
            AppendQuery(contract, methods, query.Declarations.Concat(new[] { typeParameter + " " + scopeName }).ToList(),
                query.Arguments + ", " + scopeName, "<" + typeParameter + ">", "<" + typeParameter + ">");
        }
    }

    private sealed class ScopeQuery(List<string> types, List<string> names, List<string> declarations, string arguments)
    {
        public List<string> Types { get; } = types;
        public List<string> Names { get; } = names;
        public List<string> Declarations { get; } = declarations;
        public string Arguments { get; } = arguments;
    }

    private static void AppendPartial(StringBuilder source, INamedTypeSymbol type) => source
        .Append(type.IsStatic ? "static " : "").Append("partial ")
        .Append(type.IsRecord ? (type.IsValueType ? "record struct " : "record class ") : (type.IsValueType ? "struct " : "class "))
        .Append(Escape(type.Name)).Append(TypeParameters(type)).Append(Constraints(type)).Append(" {\n");

    private static string TypeParameters(INamedTypeSymbol type) => type.TypeParameters.Length == 0 ? ""
        : "<" + string.Join(", ", type.TypeParameters.Select(parameter => Escape(parameter.Name))) + ">";

    private static string Constraints(INamedTypeSymbol type)
    {
        var result = new StringBuilder();
        foreach (var parameter in type.TypeParameters)
        {
            var constraints = new List<string>();
            if (parameter.HasUnmanagedTypeConstraint) constraints.Add("unmanaged");
            else if (parameter.HasValueTypeConstraint) constraints.Add("struct");
            else if (parameter.HasReferenceTypeConstraint)
                constraints.Add(parameter.ReferenceTypeConstraintNullableAnnotation == NullableAnnotation.Annotated ? "class?" : "class");
            else if (parameter.HasNotNullConstraint) constraints.Add("notnull");
            constraints.AddRange(parameter.ConstraintTypes.Select(TypeName));
            if (parameter.HasConstructorConstraint) constraints.Add("new()");
            if (constraints.Count > 0)
                result.Append(" where ").Append(Escape(parameter.Name)).Append(" : ").Append(string.Join(", ", constraints));
        }
        return result.ToString();
    }

    private static string AccessibilityText(Accessibility accessibility) => accessibility switch
    {
        Accessibility.Public => "public",
        Accessibility.Private => "private",
        Accessibility.Protected => "protected",
        Accessibility.ProtectedOrInternal => "protected internal",
        Accessibility.ProtectedAndInternal => "private protected",
        _ => "internal"
    };

    private static bool CanExposeConstructor(IMethodSymbol constructor, INamedTypeSymbol contract)
    {
        // Interface members are public within the interface. The constructor used to implement a member must
        // therefore be callable everywhere the generated interface itself is visible.
        return contract.DeclaredAccessibility switch
        {
            Accessibility.Public => constructor.DeclaredAccessibility == Accessibility.Public,
            Accessibility.ProtectedOrInternal => constructor.DeclaredAccessibility is
                Accessibility.Public or Accessibility.ProtectedOrInternal,
            Accessibility.Internal => constructor.DeclaredAccessibility is
                Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal,
            Accessibility.Protected => constructor.DeclaredAccessibility is
                Accessibility.Public or Accessibility.Protected or Accessibility.ProtectedOrInternal,
            Accessibility.ProtectedAndInternal => constructor.DeclaredAccessibility != Accessibility.Private,
            Accessibility.Private => true,
            _ => constructor.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal
        };
    }

    private static void Error(SourceProductionContext output, INamedTypeSymbol symbol, string reason) =>
        output.ReportDiagnostic(Diagnostic.Create(Unsupported, symbol.Locations.FirstOrDefault(), symbol.Name, reason));

    // Follow constructor forwarding instead of guessing from a parameter's name. A fixed-flag guard
    // may still have arbitrary string settings, including ones whose names contain "feature".
    private static bool ForwardsFeatureNames(IParameterSymbol parameter, Compilation compilation, HashSet<IParameterSymbol> visited)
    {
        if (!visited.Add(parameter)) return false;
        if (parameter.ContainingSymbol.ContainingType is { Name: "EngardeAttribute" } type &&
            type.ContainingNamespace.ToDisplayString() == "Engarde")
            return parameter.Name == "featureNames";

        foreach (var reference in parameter.DeclaringSyntaxReferences)
        {
            var syntax = reference.GetSyntax();
            SyntaxNode? initializer = null;
            SeparatedSyntaxList<ArgumentSyntax> arguments = default;
            if (syntax.Parent?.Parent is ConstructorDeclarationSyntax { Initializer: { } regular })
            {
                initializer = regular;
                arguments = regular.ArgumentList.Arguments;
            }
            else if (syntax.Parent?.Parent is TypeDeclarationSyntax declaration &&
                     declaration.BaseList?.Types.OfType<PrimaryConstructorBaseTypeSyntax>().FirstOrDefault() is { } primary)
            {
                initializer = primary;
                arguments = primary.ArgumentList.Arguments;
            }
            if (initializer is null) continue;
            var model = compilation.GetSemanticModel(initializer.SyntaxTree);
            if (model.GetSymbolInfo(initializer).Symbol is not IMethodSymbol target) continue;
            for (var i = 0; i < arguments.Count; i++)
            {
                var argument = arguments[i];
                if (argument.Expression is not IdentifierNameSyntax identifier ||
                    !SymbolEqualityComparer.Default.Equals(model.GetSymbolInfo(identifier).Symbol, parameter)) continue;
                var forwarded = argument.NameColon is { } name
                    ? target.Parameters.FirstOrDefault(p => p.Name == name.Name.Identifier.ValueText)
                    : target.Parameters.ElementAtOrDefault(i) ?? target.Parameters.LastOrDefault(p => p.IsParams);
                if (forwarded is not null && ForwardsFeatureNames(forwarded, compilation, visited)) return true;
            }
        }
        return false;
    }

    private static string TypeName(ITypeSymbol symbol) => symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    private static string Escape(string name) => SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;
}
