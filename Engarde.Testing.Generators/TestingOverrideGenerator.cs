using System;
using System.Collections.Generic;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Engarde.Testing.Generators;

[Generator]
public sealed class TestingOverrideGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        context.RegisterSourceOutput(context.CompilationProvider, Generate);

    private static void Generate(SourceProductionContext output, Compilation compilation)
    {
        if (compilation.GetTypeByMetadataName("Engarde.Testing.EngardeTestOverrideAttribute") is null)
            return;
        var root = compilation.GetTypeByMetadataName("Engarde.EngardeAttribute");
        if (root is null)
            return;

        output.AddSource("Engarde.Testing.Activation.g.cs", SourceText.From("""
            // <auto-generated/>
            internal static class __EngardeTestingActivation
            {
                [global::System.Runtime.CompilerServices.ModuleInitializer]
                internal static void Activate() => global::Engarde.Testing.EngardeTesting.Activate();
            }
            """, Encoding.UTF8));

        var assemblies = compilation.SourceModule.ReferencedAssemblySymbols
            .Where(assembly => assembly.Modules.Any(module => module.ReferencedAssemblySymbols
                .Any(reference => SymbolEqualityComparer.Default.Equals(reference, root.ContainingAssembly))))
            .Concat(new[] { compilation.Assembly });
        var generated = new HashSet<string>(StringComparer.Ordinal);
        var guards = assemblies.SelectMany(assembly => Types(assembly.GlobalNamespace))
            .Where(type => !SymbolEqualityComparer.Default.Equals(type, root) && IsGuard(type, root))
            .ToList();
        // Overrides go next to DisableAllEngarde, unless guards in different namespaces would share a name
        var nameCounts = guards.SelectMany(Names).GroupBy(name => name, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.Count(), StringComparer.Ordinal);
        foreach (var guard in guards)
            Generate(output, compilation, guard, nameCounts, generated);
    }

    private static string[] Names(INamedTypeSymbol guard)
    {
        var stem = guard.Name.EndsWith("Attribute", StringComparison.Ordinal)
            ? guard.Name.Substring(0, guard.Name.Length - "Attribute".Length)
            : guard.Name;
        for (var containing = guard.ContainingType; containing is not null; containing = containing.ContainingType)
            stem = containing.Name + stem;
        return new[] { stem, "I" + stem };
    }

    private static void Generate(SourceProductionContext output, Compilation compilation, INamedTypeSymbol guard,
        Dictionary<string, int> nameCounts, HashSet<string> generated)
    {
        foreach (var name in Names(guard))
        {
            var ns = nameCounts[name] == 1 ? "Engarde.Testing"
                : guard.ContainingNamespace.IsGlobalNamespace ? "" : guard.ContainingNamespace.ToDisplayString();
            var identity = ns + "." + name;
            if (!generated.Add(identity)
                || compilation.GetTypeByMetadataName((ns.Length == 0 ? "" : ns + ".") + "Enable" + name + "Attribute") is not null)
                continue;
            var target = SymbolDisplay.FormatLiteral(guard.ContainingAssembly.Name + "|" + MetadataFullName(guard), true);
            var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
            if (ns.Length != 0) source.Append("namespace ").Append(ns).Append(" {\n");
            source.Append("[global::System.AttributeUsage(global::System.AttributeTargets.Class | global::System.AttributeTargets.Method, Inherited = true, AllowMultiple = true)]\n")
                .Append("public sealed class Enable").Append(name).Append("Attribute : global::Engarde.Testing.EngardeTestOverrideAttribute { public Enable")
                .Append(name).Append("Attribute(params string[] featureNames) : base(true, ").Append(target).Append(", true, featureNames) { } }\n")
                .Append("[global::System.AttributeUsage(global::System.AttributeTargets.Class | global::System.AttributeTargets.Method, Inherited = true, AllowMultiple = true)]\n")
                .Append("public sealed class Disable").Append(name).Append("Attribute : global::Engarde.Testing.EngardeTestOverrideAttribute { public Disable")
                .Append(name).Append("Attribute(params string[] featureNames) : base(false, ").Append(target).Append(", true, featureNames) { } }\n");
            if (ns.Length != 0) source.Append("}\n");
            using var hash = SHA256.Create();
            var suffix = string.Concat(hash.ComputeHash(Encoding.UTF8.GetBytes(identity)).Select(value => value.ToString("x2")));
            output.AddSource("Engarde.Testing." + name + "." + suffix + ".g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        }
    }

    private static bool IsGuard(INamedTypeSymbol type, INamedTypeSymbol root)
    {
        for (var current = type.BaseType; current is not null; current = current.BaseType)
            if (SymbolEqualityComparer.Default.Equals(current, root)) return true;
        return false;
    }

    private static string MetadataFullName(INamedTypeSymbol type)
    {
        var containing = new Stack<string>();
        for (var current = type; current is not null; current = current.ContainingType)
            containing.Push(current.MetadataName);
        var prefix = type.ContainingNamespace.IsGlobalNamespace ? "" : type.ContainingNamespace.ToDisplayString() + ".";
        return prefix + string.Join("+", containing);
    }

    private static IEnumerable<INamedTypeSymbol> Types(INamespaceSymbol ns)
    {
        foreach (var type in ns.GetTypeMembers())
        {
            yield return type;
            foreach (var nested in Nested(type)) yield return nested;
        }
        foreach (var child in ns.GetNamespaceMembers())
            foreach (var type in Types(child)) yield return type;
    }

    private static IEnumerable<INamedTypeSymbol> Nested(INamedTypeSymbol type)
    {
        foreach (var nested in type.GetTypeMembers())
        {
            yield return nested;
            foreach (var child in Nested(nested)) yield return child;
        }
    }
}
